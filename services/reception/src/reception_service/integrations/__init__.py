"""Explicit demo/live integrations implementing the fixed service boundary."""
from __future__ import annotations

from pathlib import Path
from typing import Callable, Protocol

from ..errors import ServiceError


class IntegrationFacade(Protocol):
    def capabilities(self) -> dict: ...
    def runtime_status(self) -> dict: ...
    def resolve_identity(self, expected_seller_id: str = '') -> str: ...
    def company_profile(self, seller_id: str) -> dict: ...
    def read_recent_conversations(self, seller_id: str, before_ms: int | None = None, count: int = 20) -> dict: ...
    def read_message_page(self, seller_id: str, buyer_id: str, conversation_id: str,
                          before_ms: int | None = None, count: int = 100) -> dict: ...
    def load_photo(self, message: dict) -> dict: ...
    def observe_photo(self, message: dict, asset: dict, request_id: str,
                      *, on_start: Callable[[], None]) -> dict: ...
    def generate(self, context: dict, request_id: str, *, on_call_start=None, photo_inputs=None) -> dict: ...
    def generate_manual(self, context: dict, request_id: str, *, on_call_start=None, cancel_event=None, photo_inputs=None) -> dict: ...
    def translate(self, items: list, request_id: str, *, on_call_start=None, cancel_event=None) -> dict: ...
    def preview_send(self, intent: dict) -> dict: ...
    def send(self, intent: dict, authorization: Callable[[], bool]) -> dict: ...
    def send_chat(self, intent: dict, authorization: Callable[[], bool]) -> dict: ...
    def register(self, case: dict, previous: dict, operation_id: str,
                 *, authorization: Callable[[], bool] | None = None) -> dict: ...
    def check_registration(self) -> dict: ...
    def revoke(self) -> None: ...


def build_integrations(mode: str, data_dir: Path, settings: dict) -> IntegrationFacade:
    if mode == 'live':
        from .live import LiveIntegration
        return LiveIntegration(Path(data_dir), settings)
    raise ServiceError('invalid_mode', '只支持真实模式', stage='runtime')


__all__ = ['IntegrationFacade', 'build_integrations']
